using System.Reflection;
using System.Runtime.Loader;
using System.Text;

if (args.Length < 2)
	throw new ArgumentException("Usage: OpenRA.AotRegistry.Generator <output.cs> <assembly.dll>...");

var output = Path.GetFullPath(args[0]);
var assemblyPaths = args.Skip(1).Select(Path.GetFullPath).ToArray();
var byName = assemblyPaths.ToDictionary(p => Path.GetFileNameWithoutExtension(p), StringComparer.OrdinalIgnoreCase);
var searchDirectories = assemblyPaths.Select(Path.GetDirectoryName).Where(p => p != null).Distinct().ToArray();
AssemblyLoadContext.Default.Resolving += (_, name) =>
{
	if (name.Name != null && byName.TryGetValue(name.Name, out var path))
		return AssemblyLoadContext.Default.LoadFromAssemblyPath(path);

	foreach (var directory in searchDirectories)
	{
		var candidate = Path.Combine(directory!, name.Name + ".dll");
		if (File.Exists(candidate))
			return AssemblyLoadContext.Default.LoadFromAssemblyPath(candidate);
	}

	return null;
};

var registrations = new List<string>();
var inventory = new List<string>();
foreach (var path in assemblyPaths)
{
	var assembly = AssemblyLoadContext.Default.LoadFromAssemblyPath(path);
	foreach (var type in LoadableTypes(assembly).OrderBy(t => t.FullName, StringComparer.Ordinal))
	{
		if (!CanName(type) || type.IsAbstract || type.IsInterface || type.ContainsGenericParameters ||
			type.Namespace == "Microsoft.CodeAnalysis" || typeof(Attribute).IsAssignableFrom(type))
			continue;

		const BindingFlags flags = BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic;
		var useConstructors = type.GetConstructors(flags)
			.Where(c => c.CustomAttributes.Any(a => a.AttributeType.FullName == "OpenRA.ObjectCreator+UseCtorAttribute"))
			.ToArray();
		if (useConstructors.Length > 1)
			throw new InvalidOperationException($"Multiple UseCtor constructors on {type.FullName}.");

		if (useConstructors.Length == 1 && CanCall(useConstructors[0]))
		{
			var constructor = useConstructors[0];
			var arguments = string.Join(", ", constructor.GetParameters().Select(p =>
				$"({TypeName(p.ParameterType)})args[\"{p.Name}\"]"));
			registrations.Add($"\t\t\tGeneratedAotObjectRegistry.RegisterWithArgs(typeof({TypeName(type)}), " +
				$"static args => new {TypeName(type)}({arguments}));");
			inventory.Add(type.FullName!);
			continue;
		}

		var basic = type.GetConstructor(flags, null, Type.EmptyTypes, null);
		if (basic != null && CanCall(basic))
		{
			registrations.Add($"\t\t\tGeneratedAotObjectRegistry.RegisterBasic(typeof({TypeName(type)}), " +
				$"static () => new {TypeName(type)}());");
			inventory.Add(type.FullName!);
		}
	}
}

var source = new StringBuilder();
source.AppendLine("// <auto-generated />");
source.AppendLine("using OpenRA;");
source.AppendLine();
source.AppendLine("namespace OpenRA.iOS");
source.AppendLine("{");
source.AppendLine("\tinternal static class GeneratedAotObjectRegistryRegistration");
source.AppendLine("\t{");
source.AppendLine("\t\tinternal static readonly string[] RegisteredTypeNames =");
source.AppendLine("\t\t{");
foreach (var type in inventory.Distinct(StringComparer.Ordinal).OrderBy(t => t, StringComparer.Ordinal))
	source.AppendLine($"\t\t\t\"{type}\",");
source.AppendLine("\t\t};");
source.AppendLine();
source.AppendLine("\t\tinternal static void RegisterAll()");
source.AppendLine("\t\t{");
foreach (var registration in registrations)
	source.AppendLine(registration);
source.AppendLine("\t\t}");
source.AppendLine("\t}");
source.AppendLine("}");

Directory.CreateDirectory(Path.GetDirectoryName(output)!);
File.WriteAllText(output, source.ToString(), new UTF8Encoding(false));
Console.WriteLine($"Generated {inventory.Count} direct AOT object factories at {output}.");

static IEnumerable<Type> LoadableTypes(Assembly assembly)
{
	try
	{
		return assembly.GetTypes();
	}
	catch (ReflectionTypeLoadException e)
	{
		return e.Types.Where(t => t != null)!;
	}
}

static bool CanCall(ConstructorInfo constructor) =>
	constructor.IsPublic || constructor.IsAssembly || constructor.IsFamilyOrAssembly;

static bool CanName(Type type)
{
	for (var current = type; current != null; current = current.DeclaringType)
		if (current.IsNestedPrivate || current.IsNestedFamily || current.IsNestedFamANDAssem)
			return false;

	return true;
}

static string TypeName(Type type)
{
	if (type.IsByRef)
		return TypeName(type.GetElementType()!);
	if (type.IsArray)
		return TypeName(type.GetElementType()!) + "[]";
	if (type.IsGenericType)
	{
		var definition = type.GetGenericTypeDefinition();
		var name = (definition.FullName ?? definition.Name).Replace('+', '.');
		name = name[..name.IndexOf('`')];
		return $"global::{name}<{string.Join(", ", type.GetGenericArguments().Select(TypeName))}>";
	}

	return "global::" + (type.FullName ?? type.Name).Replace('+', '.');
}
